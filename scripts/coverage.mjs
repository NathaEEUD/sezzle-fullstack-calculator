#!/usr/bin/env node
// Coverage for both unit suites, with no dependencies.
//
//   node scripts/coverage.mjs check-go   fail if a Go package is under its threshold
//   node scripts/coverage.mjs summary    write coverage/SUMMARY.md from the committed reports
//
// Inputs: coverage/backend/coverage.out (go test -coverprofile) and
// coverage/frontend/coverage-summary.json (Vitest's json-summary reporter).

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

const MODULE = 'github.com/NathaEEUD/sezzle-fullstack-calculator/backend/'
const GO_THRESHOLDS = { 'internal/calc': 100, 'internal/httpapi': 90 }
const WEB_THRESHOLDS = { lines: 90, branches: 90 }

/** Statement coverage per package, the way `go test -cover` counts it. */
function goPackages() {
  const blocks = new Map()
  for (const line of readFileSync('coverage/backend/coverage.out', 'utf8').split('\n').slice(1)) {
    const match = line.match(/^(.+):(\d+\.\d+,\d+\.\d+) (\d+) (\d+)$/)
    if (!match) continue
    const [, file, range, statements, count] = match
    const key = `${file}:${range}`
    const covered = Number(count) > 0 || blocks.get(key)?.covered
    blocks.set(key, { pkg: dirname(file).replace(MODULE, ''), statements: Number(statements), covered })
  }
  const packages = new Map()
  for (const { pkg, statements, covered } of blocks.values()) {
    const p = packages.get(pkg) ?? { total: 0, covered: 0 }
    p.total += statements
    if (covered) p.covered += statements
    packages.set(pkg, p)
  }
  return [...packages]
    .map(([name, { total, covered }]) => ({ name, percent: total ? (100 * covered) / total : 100 }))
    .sort((a, b) => a.name.localeCompare(b.name))
}

function checkGo() {
  const failures = goPackages().filter(
    ({ name, percent }) => name in GO_THRESHOLDS && percent < GO_THRESHOLDS[name],
  )
  for (const { name, percent } of failures) {
    console.error(`coverage: ${name} is ${percent.toFixed(1)}%, below its ${GO_THRESHOLDS[name]}% threshold`)
  }
  if (failures.length) process.exit(1)
  console.log('coverage: every Go package meets its threshold')
}

function summary() {
  const pct = (n) => `${n.toFixed(1)}%`
  const threshold = (t) => (t === undefined ? 'none' : `${t}%`)
  const web = JSON.parse(readFileSync('coverage/frontend/coverage-summary.json', 'utf8')).total

  const lines = [
    '# Coverage',
    '',
    'Generated by `make coverage`. Do not edit by hand.',
    '',
    '## Service (Go, statements)',
    '',
    '| Package | Coverage | Threshold |',
    '| --- | --- | --- |',
    ...goPackages().map(
      ({ name, percent }) => `| \`${name}\` | ${pct(percent)} | ${threshold(GO_THRESHOLDS[name])} |`,
    ),
    '',
    'Report: [`backend/coverage.html`](backend/coverage.html)',
    '',
    '## App (TypeScript, `frontend/src`, `main.tsx` excluded)',
    '',
    '| Metric | Coverage | Threshold |',
    '| --- | --- | --- |',
    ...['lines', 'branches', 'statements', 'functions'].map(
      (metric) => `| ${metric} | ${pct(web[metric].pct)} | ${threshold(WEB_THRESHOLDS[metric])} |`,
    ),
    '',
    'Report: [`frontend/index.html`](frontend/index.html)',
    '',
  ]
  writeFileSync('coverage/SUMMARY.md', lines.join('\n'))
  console.log('coverage: wrote coverage/SUMMARY.md')
}

const commands = { 'check-go': checkGo, summary }
const command = commands[process.argv[2]]
if (!command) {
  console.error(`usage: node scripts/coverage.mjs ${Object.keys(commands).join('|')}`)
  process.exit(2)
}
command()
